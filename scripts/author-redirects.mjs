#!/usr/bin/env node
/**
 * Generate routes/redirects.map from the frozen route policy (MW-8).
 *
 * `collect.maar.world/*` and `tree.maar.world/*` keep working permanently. The
 * wildcard rules in policy.redirectMap say the shape; this file says the actual
 * URLs, one line per legacy address, because wildcards alone cannot be verified
 * and the `.html` and `%20` paths need to be seen to be believed.
 *
 * Reads the policy, never writes it. MW-11 configures the host from this file.
 *
 * Format is `<from-path> <to-url> <status>`, one per line, Netlify/Cloudflare
 * `_redirects` compatible. The origin is carried in a comment header per block
 * rather than in the path, because every host applies these per-domain.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/artifacts.mjs';

const policy = JSON.parse(readFileSync(join(ROOT, 'routes/policy.json'), 'utf8'));
const OUT = join(ROOT, 'routes/redirects.map');

const ORIGIN_PREFIX = {
  'collect.maar.world': '/collect',
  'tree.maar.world': '/tree',
};

const lines = [
  '# routes/redirects.map — generated by scripts/author-redirects.mjs from routes/policy.json.',
  '# Do not hand-edit: regenerate. The policy is the contract; this is its projection.',
  '#',
  '# One line per legacy URL, not a wildcard, because the .html twins and the',
  '# %20 card paths have to be individually true for the redirect to be provable.',
  '# maar.world routes are absent by design — they never moved.',
  '#',
  '#   <legacy path>  <target url>  <status>',
  '',
];

const counts = {};

for (const origin of Object.keys(ORIGIN_PREFIX)) {
  const routes = policy.routes.filter((r) => r.origin === origin);
  if (routes.length === 0) continue;

  lines.push(`# ── ${origin} ${'─'.repeat(Math.max(0, 60 - origin.length))}`);
  for (const r of routes) {
    let target;
    if (r.policy === 'redirect') {
      target = r.target;
    } else if (r.policy === 'preserve') {
      target = `https://maar.world${r.servedAt}`;
    } else {
      // Dropped: the legacy URL stops existing. Sent to the area root rather
      // than left to 404 a second time, since it is already 404 today.
      target = `https://maar.world${ORIGIN_PREFIX[origin]}`;
    }
    lines.push(`${r.url}  ${target}  301`);
    counts[origin] = (counts[origin] || 0) + 1;
  }
  lines.push('');
}

writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`routes/redirects.map: ${Object.entries(counts).map(([k, v]) => `${v} from ${k}`).join(', ')}`);
