#!/usr/bin/env node
/**
 * Generate routes/redirects.map from the frozen route policy (MW-8).
 *
 * `collect.maar.world/*` and `tree.maar.world/*` keep working permanently. The
 * wildcard rules in policy.redirectMap say the shape; this file says the actual
 * URLs, one line per legacy address, because wildcards alone cannot be verified
 * and the `.html` and `%20` paths need to be seen to be believed.
 *
 * Reads the policy, never writes it. MW-11 configures the host from this file.
 *
 * Format is `<from-path> <to-url> <status>`, one per line, Netlify/Cloudflare
 * `_redirects` compatible. The origin is carried in a comment header per block
 * rather than in the path, because every host applies these per-domain.
 *
 * ── why an undecided drop gets no line ────────────────────────────────────
 *
 * `policy === 'drop'` covers two different things. Two routes carry
 * `dropKind: 'decided'` — they already 404 in production, so sending them to the
 * area root loses nothing and is a decision on record. 254 carry
 * `dropKind: 'unresolved'`: they are live 200s whose fate is an open question,
 * each with a BLOCKED line in the ledger waiting on a human.
 *
 * This script used to send every dropped URL to the area root. When the policy
 * held 5 drops that was a footnote. It now holds 256, and regenerating naively
 * would have written 254 permanent redirects that collapse live URLs onto
 * `/collect` or `/tree` — publishing, as an instruction to a CDN, an answer
 * nobody has given. A 301 is not a note to a future maintainer: it is cached by
 * every browser and intermediary that sees it, so the wrong one is expensive to
 * take back, and the URL it erases is one somebody may be relying on.
 *
 * So they are written as inert `#` lines carrying the reason and the byte size
 * production still serves. No host acts on them, so those paths fall through to
 * the wildcard in policy.redirectMap and reach `maar.world/collect/<same path>`
 * — the same shape, not a collapse to the root. That is the least-committal
 * outcome available, and it is reversible: answering one of these questions
 * means uncommenting one line, in a commit that says so.
 *
 * The file therefore still projects all 276 Collect and Tree routes. Silence
 * about a URL would be its own kind of decision; this states the gap instead.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib/artifacts.mjs';

const policy = JSON.parse(readFileSync(join(ROOT, 'routes/policy.json'), 'utf8'));
const OUT = join(ROOT, 'routes/redirects.map');

const ORIGIN_PREFIX = {
  'collect.maar.world': '/collect',
  'tree.maar.world': '/tree',
};

/**
 * The policy's own reason, on one line.
 *
 * Not summarised and not truncated: the reason is the whole value of the
 * comment. Whoever answers one of these questions should be able to read what
 * production still serves at that path without opening another file.
 */
const reasonOf = (reason) => String(reason || 'no reason recorded').replace(/\s+/g, ' ').trim();

const lines = [
  '# routes/redirects.map — generated by scripts/author-redirects.mjs from routes/policy.json.',
  '# Do not hand-edit: regenerate. The policy is the contract; this is its projection.',
  '#',
  '# One line per legacy URL, not a wildcard, because the .html twins and the',
  '# %20 card paths have to be individually true for the redirect to be provable.',
  '# maar.world routes are absent by design — they never moved.',
  '#',
  '#   <legacy path>  <target url>  <status>',
  '#',
  '# A path marked UNDECIDED has NO active line, on purpose. It is a live 200',
  '# whose retirement nobody has authorised, and a 301 to the area root would',
  '# publish that decision to every cache that sees it. Left inert, it falls',
  '# through to the policy.redirectMap wildcard at the end of its block and keeps',
  '# its path shape. Deciding one means uncommenting one line.',
  '',
];

const counts = {};

for (const origin of Object.keys(ORIGIN_PREFIX)) {
  const routes = policy.routes.filter((r) => r.origin === origin);
  if (routes.length === 0) continue;

  const c = { redirect: 0, undecided: 0 };
  const active = [];
  const undecided = [];

  for (const r of routes) {
    if (r.policy === 'drop' && r.dropKind !== 'decided') {
      undecided.push(`# UNDECIDED  ${r.url}  — ${reasonOf(r.reason)}`);
      c.undecided += 1;
      continue;
    }

    let target;
    if (r.policy === 'redirect') {
      target = r.target;
    } else if (r.policy === 'preserve') {
      target = `https://maar.world${r.servedAt}`;
    } else {
      // dropKind: 'decided' — already 404 in production, so the area root is a
      // better answer than a second 404, and choosing it costs nothing live.
      target = `https://maar.world${ORIGIN_PREFIX[origin]}`;
    }
    active.push(`${r.url}  ${target}  301`);
    c.redirect += 1;
  }

  lines.push(`# ── ${origin} ${'─'.repeat(Math.max(0, 60 - origin.length))}`);
  lines.push(`# ${c.redirect} redirect(s), ${c.undecided} undecided and deliberately inert.`);
  lines.push(...active);

  if (undecided.length) {
    lines.push('');
    lines.push(`# ${c.undecided} live URL(s) awaiting a human decision — see MIGRATION-LEDGER.md.`);
    lines.push('# No host acts on these. They fall through to the wildcard below.');
    lines.push(...undecided);
  }

  // The wildcard is policy.redirectMap's own rule, reproduced so this file is
  // complete on its own. It must come last: first match wins.
  const wildcard = (policy.redirectMap || []).find((w) => String(w.from).startsWith(`${origin}/`));
  if (wildcard) {
    lines.push('');
    lines.push('# Catch-all from policy.redirectMap — everything not named above, including');
    lines.push('# every UNDECIDED path, keeps its shape rather than collapsing to the root.');
    lines.push(`/*  ${wildcard.to}  ${wildcard.status}`);
  }
  lines.push('');

  counts[origin] = c;
}

writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(
  `routes/redirects.map: ${Object.entries(counts)
    .map(([k, v]) => `${v.redirect} redirect + ${v.undecided} undecided from ${k}`)
    .join(', ')}`,
);
