/**
 * Every accessibility problem on one page.
 *
 * Returns a flat list of `{kind, detail}` so the report can group by kind and
 * name the worst offenders, rather than printing 133 pages of noise.
 */
export function auditPage(url, html) {
  const problems = [];
  const bad = (kind, detail) => problems.push({ kind, detail: `${url}: ${detail}` });
  const main = mainOf(html);
  const hidden = hiddenRanges(main);
  /**
   * Whether a control is hidden, and whether being hidden also took it out of
   * the tab order. `keepsTabStop` is the reportable half: hidden from readers
   * but still reachable by keyboard.
   */
  const hiddenState = (a, index) => {
    const range = rangeAt(hidden, index);
    const own = isHiddenFromAT(a);
    if (!range && !own) return { hidden: false, keepsTabStop: false };
    const unfocusable = (range && range.unfocusable) || 'hidden' in a;
    return { hidden: true, keepsTabStop: !unfocusable && a.tabindex !== '-1' };
  };

  // ---- document -----------------------------------------------------------
  const htmlTag = /<html\b[^>]*>/i.exec(html);
  const lang = htmlTag ? (attrsOf(htmlTag[0]).lang || '').trim() : '';
  if (!lang) bad('lang', 'no lang on <html> — a screen reader reads it with the wrong phonemes');

  const viewport = /<meta\b[^>]*name=["']viewport["'][^>]*>/i.exec(html);
  if (!viewport) {
    bad('viewport', 'no viewport meta — the page renders at desktop width on a phone');
  } else {
    const content = attrsOf(viewport[0]).content || '';
    if (/user-scalable\s*=\s*(no|0)/i.test(content)) bad('viewport', 'viewport disables pinch zoom');
    const maxScale = /maximum-scale\s*=\s*([\d.]+)/i.exec(content);
    if (maxScale && Number(maxScale[1]) < 2) bad('viewport', `viewport caps zoom at ${maxScale[1]}×`);
  }

  /**
   * A page that meta-refreshes elsewhere is a redirect, not a document. It has
   * no outline to get right and holding it to one would force a heading nobody
   * reads onto a page nobody sees. `/interplanetary-players` is the only one.
   */
  const isRedirectStub = /<meta\b[^>]*http-equiv=["']refresh["']/i.test(html);

  // ---- heading outline ----------------------------------------------------
  const headings = [...main.matchAll(/<h([1-6])\b[^>]*>([\s\S]*?)<\/h\1>/gi)].map((m) => ({
    level: Number(m[1]),
    text: textOf(m[2]),
  }));

  const h1s = headings.filter((h) => h.level === 1);
  if (!isRedirectStub && h1s.length !== 1) {
    bad(
      'h1',
      h1s.length === 0
        ? 'no <h1> — the page has no name in the heading outline'
        : `${h1s.length} <h1> elements (${h1s.map((h) => JSON.stringify(h.text.slice(0, 40))).join(', ')})`,
    );
  }

  let previous = 0;
  for (const h of headings) {
    if (previous && h.level > previous + 1) {
      bad('heading-skip', `h${previous} → h${h.level} at ${JSON.stringify(h.text.slice(0, 40))}`);
      break;
    }
    previous = h.level;
  }

  // ---- images and frames --------------------------------------------------
  for (const m of main.matchAll(/<img\b[^>]*>/gi)) {
    const a = attrsOf(m[0]);
    if (!('alt' in a)) bad('img-alt', `<img src="${a.src || '?'}"> has no alt attribute`);
  }

  for (const m of html.matchAll(/<iframe\b[^>]*>/gi)) {
    const a = attrsOf(m[0]);
    if (!(a.title || '').trim()) bad('iframe-title', `<iframe src="${a.src || '?'}"> has no title`);
  }

  // ---- interactive elements ----------------------------------------------
  /**
   * An accessible name, computed the way the accname spec resolves one for a
   * link or a button: aria-labelledby, then aria-label, then the element's own
   * contents (including any `alt` on an image inside it and any `<title>` on an
   * inline `<svg>`), then the `title` attribute as the last resort.
   */
  const nameOf = (a, inner) => {
    if ((a['aria-labelledby'] || '').trim()) return 'aria-labelledby';
    if ((a['aria-label'] || '').trim()) return 'aria-label';
    if (textOf(inner)) return 'contents';
    for (const img of inner.matchAll(/<img\b[^>]*>/gi)) if ((attrsOf(img[0]).alt || '').trim()) return 'image alt';
    const svgTitle = /<svg[\s\S]*?<title\b[^>]*>([\s\S]*?)<\/title>/i.exec(inner);
    if (svgTitle && textOf(svgTitle[1])) return 'svg title';
    if ((a.title || '').trim()) return 'title attribute';
    return null;
  };

  for (const m of main.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi)) {
    const a = attrsOf(`<a${m[1]}>`);
    if (!('href' in a)) continue; // an anchor without href is not a link
    const state = hiddenState(a, m.index);
    if (state.hidden) {
      if (state.keepsTabStop) bad('hidden-focusable', `aria-hidden link to ${a.href} is still in the tab order`);
      continue;
    }
    const name = nameOf(a, m[2]);
    if (!name) bad('link-name', `<a href="${a.href}"> has no accessible name`);
    /**
     * A link whose only name is its `title` attribute is a link with nothing in
     * it. It computes a name, so it is not strictly nameless — and it is also
     * invisible, zero-size, unreachable by touch and unannounced by anything
     * that does not surface `title`. Both facts are true; this reports it.
     */
    else if (name === 'title attribute') bad('empty-link', `<a href="${a.href}"> is empty — named only by title`);
  }

  for (const m of main.matchAll(/<button\b([^>]*)>([\s\S]*?)<\/button>/gi)) {
    const a = attrsOf(`<button${m[1]}>`);
    if (hiddenState(a, m.index).hidden) continue;
    if (!nameOf(a, m[2])) bad('button-name', '<button> has no accessible name');
  }

  /**
   * `<summary>` is the disclosure's own control. It is a real button to the
   * browser, so it needs a real name, and an empty one leaves the compact
   * navigation operable but unannounced.
   */
  for (const m of main.matchAll(/<summary\b([^>]*)>([\s\S]*?)<\/summary>/gi)) {
    if (!nameOf(attrsOf(`<summary${m[1]}>`), m[2])) bad('button-name', '<summary> has no accessible name');
  }

  // ---- form controls ------------------------------------------------------
  const NOT_LABELLED = new Set(['hidden', 'submit', 'button', 'reset', 'image']);
  /** `<label> Your name: <input> </label>` — the wrapping form of a label. */
  const wrapped = new Set();
  for (const m of html.matchAll(/<label\b[^>]*>([\s\S]*?)<\/label>/gi)) {
    if (!textOf(m[1])) continue;
    for (const c of m[1].matchAll(/<(input|select|textarea)\b[^>]*>/gi)) wrapped.add(c[0]);
  }
  const labelFor = new Set(
    [...html.matchAll(/<label\b[^>]*\bfor=["']([^"']+)["'][^>]*>/gi)].map((m) => m[1]),
  );

  for (const m of main.matchAll(/<(input|select|textarea)\b[^>]*>/gi)) {
    const a = attrsOf(m[0]);
    if (NOT_LABELLED.has((a.type || '').toLowerCase())) continue;
    const state = hiddenState(a, m.index);
    if (state.hidden) {
      if (state.keepsTabStop) {
        bad('hidden-focusable', `<${m[1]} name="${a.name || '?'}"> is aria-hidden but still in the tab order`);
      }
      continue;
    }
    const labelled =
      (a['aria-label'] || '').trim() ||
      (a['aria-labelledby'] || '').trim() ||
      (a.id && labelFor.has(a.id)) ||
      wrapped.has(m[0]);
    if (!labelled) bad('control-label', `<${m[1]} name="${a.name || '?'}"> has no label`);
  }

  // ---- focus order and identity ------------------------------------------
  for (const m of html.matchAll(/\btabindex\s*=\s*["'](\d+)["']/gi)) {
    if (Number(m[1]) > 0) {
      bad('tabindex', `positive tabindex=${m[1]} — it reorders the whole page's tab sequence`);
      break;
    }
  }

  const ids = [...html.matchAll(/\sid\s*=\s*["']([^"']+)["']/gi)].map((m) => m[1]);
  const seen = new Set();
  const duplicated = new Set();
  for (const id of ids) (seen.has(id) ? duplicated.add(id) : seen.add(id));
  if (duplicated.size) bad('duplicate-id', `duplicate id ${[...duplicated].slice(0, 3).map((i) => `#${i}`).join(', ')}`);

  /**
   * A fragment link to an id the page does not carry silently does nothing —
   * and the skip link is the first focusable element on all 133 pages, so if
   * anything here goes stale it is the one that matters most.
   */
  for (const m of html.matchAll(/<a\b[^>]*href\s*=\s*["']#([^"']+)["'][^>]*>/gi)) {
    if (!seen.has(m[1])) bad('dead-fragment', `link to #${m[1]} — no element carries that id`);
  }

  // ---- landmarks ----------------------------------------------------------
  const mains = (html.match(/<main\b/gi) || []).length;
  if (mains !== 1) bad('landmark', `${mains} <main> landmarks — there must be exactly one`);
  if (!/<header\b/i.test(html)) bad('landmark', 'no <header> landmark');
  if (!/<footer\b/i.test(html)) bad('landmark', 'no <footer> landmark');

  const navs = [...html.matchAll(/<nav\b[^>]*>/gi)].map((m) => attrsOf(m[0]));
  if (navs.length > 1) {
    const unnamed = navs.filter((a) => !(a['aria-label'] || '').trim() && !(a['aria-labelledby'] || '').trim());
    if (unnamed.length) bad('nav-name', `${unnamed.length} of ${navs.length} <nav> landmarks are unnamed`);
  }

  // ---- keyboard operability ----------------------------------------------
  /**
   * A control built from a click handler on a non-interactive element cannot be
   * reached by keyboard at all. Nothing on this site should have one — MW-9
   * allows application JavaScript on exactly one page — so this is both an
   * accessibility assertion and a second lock on that rule.
   */
  for (const m of html.matchAll(/\son(click|mousedown|mouseup|mouseover|keypress)\s*=/gi)) {
    bad('inline-handler', `inline on${m[1]} handler — not reachable by keyboard`);
    break;
  }

  // ---- tables -------------------------------------------------------------
  for (const m of main.matchAll(/<table\b([^>]*)>([\s\S]*?)<\/table>/gi)) {
    const a = attrsOf(`<table${m[1]}>`);
    if (a.role === 'presentation' || a.role === 'none') continue;
    if (!/<th\b/i.test(m[2])) {
      bad('table-header', `a <table> has no <th> — its rows are announced without their column`);
    }
  }

  return problems;
}

// ── colour ────────────────────────────────────────────────────────────────

const hexToRgb = (hex) => {
  const h = hex.trim().replace('#', '');
  const full = h.length === 3 ? [...h].map((c) => c + c).join('') : h;
  return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
};

/** WCAG relative luminance. */
export function luminance([r, g, b]) {
  const lin = [r, g, b].map((v) => {
    const s = v / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
}

export function contrastRatio(fg, bg) {
  const a = luminance(fg);
  const b = luminance(bg);
  const [hi, lo] = a > b ? [a, b] : [b, a];
  return (hi + 0.05) / (lo + 0.05);
}

/** `color-mix(in srgb, var(--ink) 60%, transparent)` composited over a surface. */
const composite = (fg, alpha, bg) => fg.map((c, i) => alpha * c + (1 - alpha) * bg[i]);

/**
 * Resolve the token values a surface actually renders with, from the built CSS.
 *
 * Reading the built stylesheet rather than src/styles/tokens.css is the whole
 * point: a token the bundler dropped, overrode or mangled would still be correct
 * in the source. Only two forms are supported — a hex literal and the
 * `color-mix(… N%, transparent)` derivation the token file uses — because those
 * are the only two forms the token file is allowed to contain.
 */
export function resolveSurface(css, selector) {
  const block = new RegExp(`${selector}\\s*\\{([^}]*)\\}`).exec(css);
  if (!block) return null;
  const root = /:root\s*\{([^}]*)\}/.exec(css);
  const declarations = `${root ? root[1] : ''};${block[1]}`;

  const raw = new Map();
  for (const m of declarations.matchAll(/(--[\w-]+)\s*:\s*([^;]+)/g)) raw.set(m[1], m[2].trim());

  const resolve = (name, depth = 0) => {
    if (depth > 8) return null;
    const value = raw.get(name);
    if (!value) return null;
    if (/^#[0-9a-f]{3,8}$/i.test(value)) return { rgb: hexToRgb(value), alpha: 1 };
    const varRef = /^var\(\s*(--[\w-]+)\s*\)$/.exec(value);
    if (varRef) return resolve(varRef[1], depth + 1);
    const mix = /^color-mix\(\s*in srgb\s*,\s*var\(\s*(--[\w-]+)\s*\)\s*([\d.]+)%\s*,\s*transparent\s*\)$/i.exec(value);
    if (mix) {
      const base = resolve(mix[1], depth + 1);
      return base ? { rgb: base.rgb, alpha: (Number(mix[2]) / 100) * base.alpha } : null;
    }
    return null;
  };
  return resolve;
}

