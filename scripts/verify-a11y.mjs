/**
 * Attributes of a single start tag.
 *
 * Deliberately not a parser. Every page in this build is generated by Astro
 * from content the migration normalised, so the tag soup a real parser exists to
 * survive is not present — and a dependency-free check is one that still runs in
 * five years. Boolean attributes are recorded as ''.
 */
export function attrsOf(tag) {
  const out = {};
  for (const m of tag.matchAll(/([a-zA-Z:_-][\w:.-]*)\s*=\s*("([^"]*)"|'([^']*)'|([^\s>]+))/g)) {
    out[m[1].toLowerCase()] = m[3] ?? m[4] ?? m[5] ?? '';
  }
  for (const m of tag.matchAll(/(?:\s)([a-zA-Z:_-][\w:.-]*)(?=[\s>]|\/>|$)/g)) {
    const k = m[1].toLowerCase();
    if (!(k in out)) out[k] = '';
  }
  return out;
}

/** Text a reader would hear. The one form that decodes entities properly. */
export const textOf = readableText;

/* The shell owns <main>; page content is what is inside it. mainOf is shared
   with verify:content, which had its own copy under a different name. */

/**
 * Whether an element is hidden from assistive technology.
 *
 * `aria-hidden="true"` with `tabindex="-1"` is how the index list's decorative
 * cover thumbnail is expressed: the anchor beside it carries the same
 * destination and the readable name, so a second announcement of the same link
 * would be noise. Removed from the tree AND from the tab order is a complete
 * removal; either one alone would not be, and this asserts both.
 */
const isHiddenFromAT = (a) => a['aria-hidden'] === 'true' || 'hidden' in a;

/**
 * The character ranges covered by an `aria-hidden="true"` subtree.
 *
 * `aria-hidden` is inherited, so the attribute on the element itself is only
 * half the question. Mailchimp's bot honeypot is the case that proves it: a
 * bare `<input name="b_…">` with no label at all, which is correct — it sits
 * inside `<div style="left:-5000px" aria-hidden="true">` and carries
 * `tabindex="-1"`, so no reader announces it and no keyboard reaches it.
 * Labelling it would be worse than not, and a check that demanded a label there
 * would be demanding a defect.
 *
 * Matching is by tag nesting from the opening tag; a subtree that never closes
 * runs to the end of the document, which is the conservative direction — it
 * suppresses findings rather than inventing them, and any focusable element
 * inside it is still asserted by `hidden-focusable`.
 *
 * Each range records whether it is also *unfocusable*. `aria-hidden` alone
 * removes an element from the accessibility tree but leaves it in the tab
 * order, which is the worst of both — a keyboard user lands on something no
 * reader will announce. `display:none`, `visibility:hidden` and the `hidden`
 * attribute remove it from both, so a region carrying one of those needs no
 * `tabindex="-1"` on the things inside it. The legacy `.pdf-fallback` block is
 * exactly this shape and is correct as it stands.
 */
export function hiddenRanges(html) {
  const ranges = [];
  for (const open of html.matchAll(/<([a-z][\w-]*)\b[^>]*\baria-hidden\s*=\s*["']true["'][^>]*>/gi)) {
    const tag = open[1].toLowerCase();
    if (/^(img|input|br|hr|meta|link|source|track|area|col|embed|param|wbr|base)$/.test(tag)) continue;
    if (open[0].endsWith('/>')) continue;
    const a = attrsOf(open[0]);
    const unfocusable =
      'hidden' in a || /display\s*:\s*none|visibility\s*:\s*hidden/i.test(a.style || '');
    let depth = 1;
    const nested = new RegExp(`<(/?)${tag}\\b[^>]*>`, 'gi');
    nested.lastIndex = open.index + open[0].length;
    let m;
    while ((m = nested.exec(html))) {
      depth += m[1] ? -1 : 1;
      if (depth === 0) break;
    }
    ranges.push({ start: open.index, end: m ? m.index + m[0].length : html.length, unfocusable });
  }
  return ranges;
}

const rangeAt = (ranges, index) => ranges.find((r) => index >= r.start && index < r.end) || null;

