#!/usr/bin/env node
/**
 * verify:a11y — the accessibility and responsive gates of MW-11, as assertions.
 *
 * MW-11 lists "keyboard navigation across every interactive element", "visible
 * focus states in every context", "heading hierarchy and landmarks correct",
 * "contrast meets WCAG 2.2 AA", "prefers-reduced-motion honoured" and "long
 * Spanish copy and unbroken URLs wrap safely" under *human* review gates, and
 * they do need a human eye. But a human reviewing 133 pages once, by hand, at a
 * single point in time, is not a gate — it is a snapshot. The next migration run
 * regenerates every body from the legacy checkouts and nothing would notice if a
 * heading level, an iframe title or an image alt went missing again.
 *
 * So the mechanical half is asserted here and runs on every build. What is left
 * for the human is what genuinely needs judgement: whether an alt text is a good
 * description, whether a focus ring is legible against a photograph, whether the
 * reading order makes sense. This check does not claim to be that review, and
 * the ledger records the human gates separately.
 *
 * Everything is measured against dist/ — what actually ships — and against the
 * built CSS rather than the sources, so a rule that the bundler dropped cannot
 * pass by existing in src/.
 *
 * WHAT THIS DELIBERATELY DOES NOT DO: it does not run a headless browser and it
 * does not compute layout. Horizontal overflow at 360/768/1024/1440 CSS px is a
 * layout question, and it was measured in a real browser at MW-11 sign-off; the
 * ledger entry `MW-11 a11y/responsive-sweep` records the numbers. The static
 * proxies for it here (a zoomable viewport, media bounded to its container,
 * wide content in its own scroll container, unbroken strings allowed to break)
 * are what a build can honestly assert without one.
 */

