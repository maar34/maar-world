/**
 * The class names of every CSS rule that paints with a given token.
 *
 * Used by `onlyWherePainted`, which exists for exactly one role. `--ink-faint`
 * composites to 3.32:1 over the dark surface and 2.56:1 over paper, because 40%
 * of cream over near-black and 40% of near-black over cream are not symmetric.
 * Asserting it unconditionally on paper would demand a token change, and token
 * values come from the design spec rather than from a check; asserting it
 * nowhere would let it become body copy unnoticed. So it is asserted on any
 * surface that has a page carrying an element the token is painted on — today
 * the glyph runs and the Helix diagram, all of which are dark — and the report
 * names the pairs it did not measure rather than passing over them in silence.
 */
export function classesPainting(css, token) {
  const classes = new Set();
  const uses = new RegExp(`var\\(\\s*${token}\\s*[,)]`);
  for (const rule of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    if (!uses.test(rule[2])) continue;
    for (const c of rule[1].matchAll(/\.([\w-]+)/g)) classes.add(c[1]);
  }
  return classes;
}

/**
 * The surfaces, and the attribute a page carries to select each one.
 *
 * There is one. `paper` was a second entry here until MW-16: a cream surface
 * selected by `surface: paper` in a record's frontmatter, used by nine
 * documentation articles. The owner had those moved to dark — the docs were
 * the one part of the site that turned white under the reader — and then
 * removed the surface itself, so `layouts/shell-paper`, the
 * `[data-surface='paper']` token block and the frontmatter field are all gone.
 * Nothing can select it, so measuring it would be reporting on pixels that
 * cannot exist.
 *
 * The list is still a list, and `pagesOnSurface` still groups by the attribute,
 * because the shape is what makes the check honest: only surfaces a page in
 * `dist/` actually renders are measured, and the report names which those were.
 * A second surface added tomorrow starts being asserted on the run that ships
 * it, without this file changing shape.
 *
 * `@media print` is deliberately NOT here. Its contrast is a different question
 * — ink on real paper, not composited pixels — and this check measures what a
 * screen shows.
 */
const SURFACES = [{ name: 'dark', selector: ':root', attribute: 'dark' }];

/** The pages a given surface is actually painted on. */
const pagesOnSurface = (documents, attribute) =>
  documents.filter((html) => {
    const tag = /<html\b[^>]*>/i.exec(html);
    const surface = tag ? attrsOf(tag[0])['data-surface'] : undefined;
    return (surface || 'dark') === attribute;
  });

// ── the check ─────────────────────────────────────────────────────────────

export async function checkA11y(report) {
  if (!existsSync(ARTIFACTS.dist.path)) {
    report.skip('accessibility gates', ARTIFACTS.dist.rel, ARTIFACTS.dist.issue);
    return;
  }

  const { files } = indexDist();
  const pages = files.filter((f) => f.endsWith('.html'));
  if (!pages.length) {
    report.skip('accessibility gates', `${ARTIFACTS.dist.rel} (no HTML pages)`, ARTIFACTS.dist.issue);
    return;
  }

  const byKind = new Map();
  const documents = [];
  for (const file of pages) {
    const url = `/${file.replace(/index\.html$/, '').replace(/\.html$/, '')}`;
    const html = readFileSync(join(ARTIFACTS.dist.path, file), 'utf8');
    documents.push(html);
    for (const p of auditPage(url, html)) {
      if (!byKind.has(p.kind)) byKind.set(p.kind, []);
      byKind.get(p.kind).push(p.detail);
    }
  }

  /** One assertion per kind, so a failure names the defect rather than a count. */
  const ASSERTIONS = [
    ['lang', 'every page declares its own language'],
    ['viewport', 'every page is zoomable at its own width'],
    ['h1', 'every page has exactly one <h1>'],
    ['heading-skip', 'no page skips a heading level'],
    ['img-alt', 'every image carries an alt attribute'],
    ['iframe-title', 'every frame carries a title'],
    ['link-name', 'every link has an accessible name'],
    ['empty-link', 'no link is an empty target'],
    ['button-name', 'every button and disclosure has an accessible name'],
    ['control-label', 'every form control has a label'],
    ['hidden-focusable', 'nothing hidden from assistive technology keeps a tab stop'],
    ['tabindex', 'no positive tabindex reorders the tab sequence'],
    ['duplicate-id', 'ids are unique within a page'],
    ['dead-fragment', 'every in-page link points at an element that exists'],
    ['landmark', 'every page carries header, main and footer landmarks'],
    ['nav-name', 'every navigation landmark is named'],
    ['inline-handler', 'no control is built from an inline event handler'],
    ['table-header', 'every data table has header cells'],
  ];

  for (const [kind, label] of ASSERTIONS) {
    const found = byKind.get(kind) || [];
    if (!found.length) {
      report.pass(label, `${pages.length} pages`);
    } else {
      report.fail(
        label,
        `${found.length} on ${new Set(found.map((d) => d.split(':')[0])).size} page(s) — ` +
          found.slice(0, 3).join(' / ') +
          (found.length > 3 ? ` … and ${found.length - 3} more` : ''),
      );
    }
  }

  // ---- stylesheet-level gates --------------------------------------------
  /**
   * Every rule that ships, from both places rules ship.
   *
   * Astro emits a component's scoped `<style>` inline in the page when it is
   * small enough and into an external stylesheet when it is not, and which of
   * the two it picks is a bundler decision that can change between builds. A
   * check that read only `dist/**\/*.css` would have concluded that the glyph
   * runs are painted on no page at all — the rule that paints them is inline on
   * each of the 35 card pages.
   */
  const css = files.filter((f) => f.endsWith('.css')).map((f) => readFileSync(join(ARTIFACTS.dist.path, f), 'utf8'));
  const inline = documents.flatMap((html) => [...html.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map((m) => m[1]));
  const allCss = [...css, ...inline].join('\n');

  if (!allCss.trim()) {
    report.skip('stylesheet accessibility gates', 'no CSS in dist/', 'MW-2');
    return;
  }

  /**
   * "focus is always a visible outline, never a shadow, never removed."
   * `outline: none` inside a rule that immediately supplies another outline is
   * a legitimate reset; one that does not is a removed focus ring.
   */
  const strippedFocus = [];
  for (const m of allCss.matchAll(/([^{}]*focus[^{}]*)\{([^}]*)\}/gi)) {
    const body = m[2];
    if (!/outline\s*:\s*(none|0)\b/i.test(body)) continue;
    if (/outline(-width|-style|-color)?\s*:\s*(?!none|0\b)/i.test(body.replace(/outline\s*:\s*(none|0)\b[^;]*;?/i, ''))) continue;
    strippedFocus.push(m[1].trim().slice(0, 60));
  }
  if (strippedFocus.length) {
    report.fail('the focus ring is never removed', `${strippedFocus.length} rule(s): ${strippedFocus.slice(0, 2).join(' / ')}`);
  } else {
    report.pass('the focus ring is never removed', `${css.length} stylesheets, ${inline.length} inline blocks`);
  }

  if (!/:focus-visible[^{]*\{[^}]*outline\s*:/i.test(allCss)) {
    report.fail('a visible focus ring is defined', 'no :focus-visible rule sets an outline');
  } else {
    report.pass('a visible focus ring is defined');
  }

  if (!/@media[^{]*prefers-reduced-motion\s*:\s*reduce/i.test(allCss)) {
    report.fail('prefers-reduced-motion is honoured', 'no (prefers-reduced-motion: reduce) block ships');
  } else {
    report.pass('prefers-reduced-motion is honoured');
  }

  /**
   * "long Spanish copy and unbroken URLs wrap safely" (MW-11). A legacy body
   * carries bare URLs, and a token wider than a 360px viewport pushes the whole
   * document sideways — the one overflow a media query cannot fix, because the
   * element is not the one that is too wide.
   */
  if (!/overflow-wrap\s*:\s*(break-word|anywhere)/i.test(allCss)) {
    report.fail('unbroken words and URLs are allowed to wrap', 'no overflow-wrap declaration ships');
  } else {
    report.pass('unbroken words and URLs are allowed to wrap');
  }

  /** Wide content gets its own scroll container instead of widening the page. */
  const scrollable = /(pre|table)[^{}]*\{[^}]*overflow-x\s*:\s*auto/i.test(allCss);
  if (!scrollable) {
    report.fail('wide content scrolls inside itself', 'no overflow-x:auto container for <pre>/<table>');
  } else {
    report.pass('wide content scrolls inside itself');
  }

  // ---- contrast ------------------------------------------------------------
  const failures = [];
  const measured = [];
  const notMeasured = [];
  const surfaces = SURFACES.map((s) => ({ ...s, pages: pagesOnSurface(documents, s.attribute) })).filter(
    (s) => s.pages.length,
  );

  for (const { name, selector, pages: surfacePages } of surfaces) {
    const resolve = resolveSurface(allCss, selector);
    if (!resolve) {
      failures.push(`${name}: no token block matching ${selector} in the built CSS`);
      continue;
    }
    for (const pair of CONTRAST_PAIRS) {
      if (pair.onlyWherePainted) {
        const classes = [...classesPainting(allCss, pair.fg)];
        const painted =
          classes.length > 0 &&
          surfacePages.some((html) => classes.some((c) => new RegExp(`class=["'][^"']*\\b${c}\\b`).test(html)));
        if (!painted) {
          notMeasured.push(`${pair.fg} on ${name} (painted on no ${name} page)`);
          continue;
        }
      }
      const fg = resolve(pair.fg);
      const bg = resolve(pair.bg);
      if (!fg || !bg) {
        failures.push(`${name}: cannot resolve ${!fg ? pair.fg : pair.bg}`);
        continue;
      }
      if (bg.alpha !== 1) {
        failures.push(`${name}: ${pair.bg} is not opaque — contrast against it is undefined`);
        continue;
      }
      const ratio = contrastRatio(composite(fg.rgb, fg.alpha, bg.rgb), bg.rgb);
      measured.push(ratio);
      if (ratio < pair.min) {
        failures.push(
          `${name}: ${pair.fg} on ${pair.bg} (${pair.what}) is ${ratio.toFixed(2)}:1, below ${pair.min}:1`,
        );
      }
    }
  }
  if (failures.length) {
    report.fail('text and focus meet WCAG 2.2 AA contrast', failures.slice(0, 3).join(' / '));
  } else {
    report.pass(
      'text and focus meet WCAG 2.2 AA contrast',
      `${measured.length} pairs on the ${surfaces.map((s) => `${s.name} (${s.pages.length})`).join(' and ')} ` +
        `surface${surfaces.length > 1 ? 's' : ''}, lowest ${Math.min(...measured).toFixed(2)}:1` +
        (notMeasured.length ? ` — not measured: ${notMeasured.join(', ')}` : ''),
    );
  }
}

if (process.argv[1] && process.argv[1].endsWith('verify-a11y.mjs')) {
  runStandalone('verify:a11y', checkA11y);
}
